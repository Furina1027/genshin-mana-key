namespace ManaKeyDumper.Tests;

/// <summary>
/// 序言判据（挂钩前的最后一道门）测试。
///
/// 数据是**从真实 `YuanShen.exe` 里读出来的原始字节**，不是手写的理想样本：
///   · Cn 组 = 修复后源码里 14 个国服 RVA 处的 16 字节 → 必须全部通过（不能误杀真钩子）；
///   · "错服"组 = 国际服那 5 个 RVA 落在**国服** exe 里的字节 —— 这是"版本/服务器不匹配导致
///     RVA 失效"的真实样本 → 必须全部拒绝。
///
/// 其中 `NativeSetFile` 那组是 `48 B8 01 00 00 00 02 00 …`（mov rax, imm64）：
/// 首字节恰好是 0x48，**旧的一字节判据会放行**，MinHook 就会去改别的函数的中段机器码。
/// 本文件的回归用例专门钉住这一点。
/// </summary>
public sealed class PrologueTests {

    private static readonly (string Name, byte[] Bytes)[] CnPrologues = [
        ("SetVideoAudioKeys", [0x55, 0x56, 0x57, 0x53, 0x48, 0x83, 0xEC, 0x68, 0x48, 0x8D, 0x6C, 0x24, 0x60, 0x48, 0xC7, 0x45]),
        ("SetVideoAesKeyAudio", [0x55, 0x56, 0x57, 0x53, 0x48, 0x83, 0xEC, 0x78, 0x48, 0x8D, 0x6C, 0x24, 0x70, 0x48, 0xC7, 0x45]),
        ("NativeSetVideoAudioKeys", [0x55, 0x56, 0x57, 0x53, 0x48, 0x83, 0xEC, 0x68, 0x48, 0x8D, 0x6C, 0x24, 0x60, 0x48, 0xC7, 0x45]),
        ("NativeSetVideoAesKeyAudio", [0x55, 0x56, 0x57, 0x53, 0x48, 0x83, 0xEC, 0x68, 0x48, 0x8D, 0x6C, 0x24, 0x60, 0x48, 0xC7, 0x45]),
        ("NativeSetFile", [0x55, 0x56, 0x57, 0x53, 0x48, 0x83, 0xEC, 0x68, 0x48, 0x8D, 0x6C, 0x24, 0x60, 0x48, 0xC7, 0x45]),
        ("ManagedSetFile", [0x41, 0x56, 0x56, 0x57, 0x53, 0x48, 0x83, 0xEC, 0x28, 0x44, 0x89, 0xCF, 0x4C, 0x89, 0xC6, 0x49]),
        ("Unk5", [0x56, 0x57, 0x53, 0x48, 0x83, 0xEC, 0x50, 0x4C, 0x89, 0xC6, 0x48, 0x89, 0xD7, 0x89, 0xCB, 0x48]),
        ("Unk6", [0x56, 0x57, 0x53, 0x48, 0x83, 0xEC, 0x50, 0x4C, 0x89, 0xC6, 0x48, 0x89, 0xD3, 0x89, 0xCF, 0x48]),
        ("KeyFeed", [0x56, 0x57, 0x48, 0x83, 0xEC, 0x28, 0x48, 0x89, 0xCE, 0x48, 0x8B, 0x49, 0x30, 0x48, 0x85, 0xC9]),
        ("DecrypterInitConfig", [0x48, 0x83, 0xEC, 0x28, 0x48, 0x85, 0xC9, 0x74, 0x19, 0x48, 0x8B, 0x41, 0x10, 0x0F, 0xB6, 0x51]),
