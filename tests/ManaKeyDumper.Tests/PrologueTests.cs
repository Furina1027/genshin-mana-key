    /// <summary>国际服的 RVA 落在国服 exe 里读出来的字节 —— 即"错服/失效 RVA"的真实样本。</summary>
    private static readonly (string Name, byte[] Bytes)[] StaleEntries = [
        ("SetVideoAudioKeys", [0x89, 0xC1, 0x31, 0xD2, 0x45, 0x31, 0xC0, 0x45, 0x31, 0xC9, 0xE8, 0xD1, 0x77, 0x0A, 0x00, 0x48]),
        ("SetVideoAesKeyAudio", [0x85, 0x0A, 0xFD, 0xFF, 0xFF, 0xE9, 0x9E, 0xFC, 0xFF, 0xFF, 0xE8, 0xF1, 0x81, 0x46, 0xF9, 0xB9]),
        ("NativeSetVideoAudioKeys", [0x00, 0x0F, 0x84, 0x45, 0x03, 0x00, 0x00, 0x48, 0x85, 0xF6, 0x0F, 0x84, 0x56, 0x03, 0x00, 0x00]),
        ("NativeSetVideoAesKeyAudio", [0xF9, 0xEB, 0xA6, 0xB9, 0x77, 0x34, 0x00, 0x00, 0xE8, 0xF3, 0x28, 0x4D, 0xF9, 0xC6, 0x05, 0xD3]),
        ("NativeSetFile", [0x48, 0xB8, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00, 0x00, 0x00, 0x48, 0x89, 0x44, 0x24, 0x50, 0xC7]),
    ];

    [Fact]
    public void WindowSize_MatchesTestData() {
        Assert.Equal(16, Prologue.WindowSize);
        Assert.All(CnPrologues, e => Assert.Equal(Prologue.WindowSize, e.Bytes.Length));
        Assert.All(StaleEntries, e => Assert.Equal(Prologue.WindowSize, e.Bytes.Length));
    }

    /// <summary>真实国服的 14 个钩子一个都不能被误杀 —— 否则工具会"静默少挂钩"。</summary>
    [Fact]
    public void RealCnPrologues_AllPass() {
        foreach (var (name, bytes) in CnPrologues) {
            Assert.True(Prologue.LooksLikeFunctionEntry(bytes),
                $"{name} 是真实 exe 里读出的函数入口，判据不该拒绝它");
        }
    }

    /// <summary>失效/错服的 RVA 必须全部拒绝。</summary>
    [Fact]
    public void StaleOrWrongServerEntries_AreRejected() {
        foreach (var (name, bytes) in StaleEntries) {
            Assert.False(Prologue.LooksLikeFunctionEntry(bytes),
                $"{name} 的错服样本（首字节 0x{bytes[0]:X2}）不是函数入口，必须拒绝");
        }
    }

    /// <summary>
    /// 回归：旧的一字节判据会放行 `48 B8 …`（mov rax, imm64），
    /// 那会让 MinHook 改掉别的函数的中段机器码。这里把"旧判据的漏洞"和
    /// "新判据挡住了"同时钉住，避免以后有人把判据改回一字节版本。
    /// </summary>
    [Fact]
    public void MovRaxImm64_IsRejected_AlthoughOldOneByteRuleAcceptedIt() {
        byte[] bytes = [0x48, 0xB8, 0x01, 0x00, 0x00, 0x00, 0x02, 0x00,
                        0x00, 0x00, 0x48, 0x89, 0x44, 0x24, 0x50, 0xC7];

        static bool OldOneByteRule(byte b) =>
            b is 0x55 or 0x53 or 0x56 or 0x57 or 0x41 or 0x48;

        Assert.True(OldOneByteRule(bytes[0]), "旧判据确实会放行（这就是要加强的原因）");
        Assert.False(Prologue.LooksLikeFunctionEntry(bytes), "新判据必须拒绝它");
    }

    /// <summary>常见序言形态要认得出来（避免把判据收得过窄而误杀）。</summary>
    [Fact]
    public void CommonPrologueShapes_AreAccepted() {
        byte[][] accepted = [
            [0x48, 0x83, 0xEC, 0x28, 0x48, 0x85, 0xC9, 0x74, 0x19, 0x48, 0x8B, 0x41, 0x10, 0x0F, 0xB6, 0x51], // sub rsp, 0x28
            [0x55, 0x48, 0x89, 0xE5, 0x48, 0x83, 0xEC, 0x20, 0x48, 0x89, 0x4D, 0xF8, 0x48, 0x8B, 0xC1, 0xC3], // push rbp; mov rbp,rsp
            [0x41, 0x57, 0x41, 0x56, 0x41, 0x55, 0x41, 0x54, 0x56, 0x57, 0x55, 0x53, 0x48, 0x83, 0xEC, 0x48], // 长 push 串 + sub rsp
            [0x48, 0x89, 0x4C, 0x24, 0x08, 0x48, 0x89, 0x54, 0x24, 0x10, 0x48, 0x83, 0xEC, 0x28, 0xC3, 0xCC], // home rcx/rdx
            [0xF3, 0x0F, 0x1E, 0xFA, 0x48, 0x83, 0xEC, 0x38, 0x48, 0x8B, 0xC4, 0xC3, 0xCC, 0xCC, 0xCC, 0xCC], // endbr64
            [0x48, 0x8B, 0xC4, 0x48, 0x89, 0x58, 0x08, 0x48, 0x83, 0xEC, 0x20, 0xC3, 0xCC, 0xCC, 0xCC, 0xCC], // mov rax,rsp
        ];
        for (var i = 0; i < accepted.Length; i++) {
            Assert.True(Prologue.LooksLikeFunctionEntry(accepted[i]), $"第 {i} 个常见序言形态被误杀");
        }
    }

    [Fact]
    public void TruncatedOrEmptyInput_IsRejected() {
        Assert.False(Prologue.LooksLikeFunctionEntry([]));
        Assert.False(Prologue.LooksLikeFunctionEntry([0x48, 0x83, 0xEC, 0x28]));
        Assert.False(Prologue.LooksLikeFunctionEntry(new byte[Prologue.WindowSize - 1]));
    }

    [Fact]
    public void AllZeroWindow_IsRejected() {
        Assert.False(Prologue.LooksLikeFunctionEntry(new byte[Prologue.WindowSize]));
    }

}
